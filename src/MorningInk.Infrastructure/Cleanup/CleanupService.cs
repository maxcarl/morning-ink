using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using MorningInk.Application.Publishing;
using MorningInk.Infrastructure.Persistence;
using MorningInk.Infrastructure.Profiles;

namespace MorningInk.Infrastructure.Cleanup;

/// <summary>Deletes what is past its retention: old issues (not pinned) with their files, seen articles, images and backups.</summary>
public sealed partial class CleanupService(
    MorningInkDbContext db,
    IOptions<RetentionOptions> retention,
    IOptions<StorageOptions> storage,
    TimeProvider time,
    ProfileLocks locks,
    ILogger<CleanupService> logger)
{
    public async Task<CleanupReport> RunAsync(CancellationToken cancellationToken)
    {
        var options = retention.Value;
        var now = time.GetUtcNow();

        // The record of what went to the AI is kept as long as the issues it was for.
        await db.AiCalls.Where(c => c.At < now.AddDays(-options.IssueDays)).ExecuteDeleteAsync(cancellationToken);

        var report = new CleanupReport(
            Issues: await DeleteIssuesAsync(now.AddDays(-options.IssueDays), cancellationToken),
            SeenArticles: await db.SeenArticles.Where(s => s.SeenAt < now.AddDays(-options.SeenArticleDays)).ExecuteDeleteAsync(cancellationToken),
            // A build reuses cached images by their hash and reads them from disk when rendering, however old they are;
            // while one runs, the images wait for the next night, so the cleanup time never has to dodge the editions.
            Images: locks.AnyHeld ? 0 : DeleteFilesOlderThan(storage.Value.ImageDirectory, now.AddDays(-options.ImageDays)),
            Backups: DeleteOldBackups(storage.Value.BackupDirectory, options.KeepBackups));
        LogReport(logger, report.Issues, report.SeenArticles, report.Images, report.Backups);
        return report;
    }

    private async Task<int> DeleteIssuesAsync(DateTimeOffset cutoff, CancellationToken cancellationToken)
    {
        var expired = await db.Issues
            .Where(i => !i.Pinned && i.CreatedAt < cutoff)
            .Select(i => new { i.Id, i.FileName })
            .ToListAsync(cancellationToken);
        if (expired.Count == 0)
        {
            return 0;
        }

        // Rows first: a file without a row is harmless, a row pointing at a deleted file would be resent as broken.
        var ids = expired.Select(i => i.Id).ToList();
        await db.Issues.Where(i => ids.Contains(i.Id)).ExecuteDeleteAsync(cancellationToken); // entries and attempts cascade
        foreach (var fileName in expired.Select(i => i.FileName).OfType<string>())
        {
            // The name was generated by Morning Ink, but GetFileName keeps the path inside the issue directory regardless.
            var path = Path.Combine(storage.Value.IssueDirectory, Path.GetFileName(fileName));
            DeleteFile(path);
            DeleteFile(IssueArchive.CoverPathFor(path));
        }

        return expired.Count;
    }

    private static int DeleteFilesOlderThan(string directory, DateTimeOffset cutoff)
    {
        if (!Directory.Exists(directory))
        {
            return 0;
        }

        var old = new DirectoryInfo(directory).EnumerateFiles().Where(f => f.LastWriteTimeUtc < cutoff.UtcDateTime).ToList();
        old.ForEach(f => DeleteFile(f.FullName));
        return old.Count;
    }

    // Backup names carry a sortable timestamp (morning-ink-yyyyMMdd-HHmmss-fff.db), so the name order is the age order.
    private static int DeleteOldBackups(string directory, int keep)
    {
        if (!Directory.Exists(directory))
        {
            return 0;
        }

        var old = Directory.GetFiles(directory, "morning-ink-*.db").Order(StringComparer.Ordinal).SkipLast(keep).ToList();
        old.ForEach(DeleteFile);
        return old.Count;
    }

    private static void DeleteFile(string path)
    {
        try
        {
            File.Delete(path);
        }
        catch (IOException)
        {
            // Still open somewhere, e.g. an image being converted right now: the next run gets it.
        }
    }

    [LoggerMessage(Level = LogLevel.Information, Message = "Cleanup deleted {Issues} issues, {SeenArticles} seen articles, {Images} images and {Backups} backups")]
    private static partial void LogReport(ILogger logger, int issues, int seenArticles, int images, int backups);
}
